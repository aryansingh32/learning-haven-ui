"""Builds out/courses.json and out/import_courses.sql (unpublished draft courses).
    python3 build_courses.py
Checks: every code snippet in the DSA course runs against its asserts; every practice title exists in
problems.json; every aptitude quiz question comes from the verified bank.
"""
import json, os, random, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import courses_dsa as D, courses_aptitude as A

here = os.path.dirname(os.path.abspath(__file__))
problems = json.load(open(os.path.join(here, 'out', 'problems.json')))
titles = {p['title'] for p in problems}
bank = json.load(open(os.path.join(here, 'out', 'aptitude.json')))
mock_hashes = {h for m in bank['mocks'] for s in m['sections'] for h in s['hashes']}
rng = random.Random(11)

def quiz_item(b):
    texts = {o['id']: o['text'] for o in b['options']}
    return {'question': b['body'], 'options': [o['text'] for o in b['options']], 'correctAnswer': texts[b['correct_id']], 'explanation': b['explanation']}

courses = []
# ── DSA ──
chapters = []
for i, (title, tag, diff, hook, mins, lesson, code, test, quiz, practice) in enumerate(D.CH, 1):
    ns = {}
    try:
        exec(code + '\n' + test, ns)
    except Exception as e:
        sys.exit(f'DSA chapter {i} "{title}": snippet failed: {e!r}')
    for t in practice:
        assert t in titles, f'DSA chapter {i}: practice problem "{t}" does not exist in problems.json'
    for q, opts, correct, why in quiz:
        assert correct in opts and len(set(opts)) == len(opts), f'{title}: bad quiz item {q}'
    steps = [
        ('story_hook', 'Story', {'story': hook}),
        ('doc', 'Lesson', {'doc_md': lesson}),
        ('quiz', 'Check your understanding', {'quiz_questions': [{'question': q, 'options': o, 'correctAnswer': c, 'explanation': w} for q, o, c, w in quiz]}),
        ('task', 'Practice', {'task_prompt': 'Open Practice and solve these problems, which all use this pattern: ' + '; '.join(practice) + '. Write down, in one sentence, why the pattern fits each one.'}),
    ]
    chapters.append(dict(title=title, topic_tag=tag, difficulty=diff, hook=hook, minutes=mins, steps=steps))
courses.append(dict(**D.COURSE, chapters=chapters))

# ── Aptitude ──
chapters = []
for i, (title, tag, diff, hook, mins, lesson, topics) in enumerate(A.CH, 1):
    pool = [b for b in bank['questions'] if b['topic'] in topics]
    fresh = [b for b in pool if b['hash'] not in mock_hashes]  # keep the mock questions unseen where possible
    rng.shuffle(fresh); rest = [b for b in pool if b not in fresh]; rng.shuffle(rest)
    pick = (fresh + rest)[:6]
    assert len(pick) >= 5, f'aptitude chapter {title}: only {len(pick)} questions for {topics}'
    steps = [
        ('story_hook', 'Story', {'story': hook}),
        ('doc', 'Lesson', {'doc_md': lesson}),
        ('quiz', 'Practice quiz', {'quiz_questions': [quiz_item(b) for b in pick]}),
        ('task', 'Take it further', {'task_prompt': 'Make up two questions of your own on this topic, solve them, and swap with a friend. Then try the matching section of a Placement Aptitude mock test.'}),
    ]
    chapters.append(dict(title=title, topic_tag=tag, difficulty=diff, hook=hook, minutes=mins, steps=steps))
courses.append(dict(**A.COURSE, chapters=chapters))

os.makedirs(os.path.join(here, 'out'), exist_ok=True)
json.dump(courses, open(os.path.join(here, 'out', 'courses.json'), 'w'), indent=1, ensure_ascii=False)

def q(s): return "E'" + s.replace('\\', '\\\\').replace("'", "''").replace('\n', '\\n') + "'"
sql = ['-- DRAFT content import: courses (created UNPUBLISHED). NOT a migration — run by hand after review of',
       '-- content/drafts/out/courses.json. Publish a course afterwards with: update public.courses set is_published = true where slug = ...',
       '-- Re-runnable: a course whose slug already exists is skipped entirely.',
       '-- Generated by content/drafts/build_courses.py. Do not edit by hand.', 'begin;', '']
for c in courses:
    sql.append(f"""do $$
declare cid uuid; chid uuid;
begin
  if exists (select 1 from public.courses where slug = {q(c['slug'])}) then return; end if;
  insert into public.courses (title, slug, description, type, difficulty_level, is_premium, is_published, item_count)
  values ({q(c['title'])}, {q(c['slug'])}, {q(c['description'])}, 'topic_wise', {q(c['difficulty'])}, false, false, {len(c['chapters'])}) returning id into cid;""")
    for n, ch in enumerate(c['chapters'], 1):
        sql.append(f"""  insert into public.chapters (course_id, chapter_number, title, topic_tag, difficulty, story_hook, est_minutes, is_active)
  values (cid, {n}, {q(ch['title'])}, {q(ch['topic_tag'])}, {q(ch['difficulty'])}, {q(ch['hook'])}, {ch['minutes']}, true) returning id into chid;""")
        for sn, (stype, stitle, content) in enumerate(ch['steps'], 1):
            sql.append(f"  insert into public.steps (chapter_id, step_number, type, title, content) values (chid, {sn}, {q(stype)}, {q(stitle)}, {q(json.dumps(content, ensure_ascii=False))}::jsonb);")
    sql.append('end $$;\n')
sql += ['commit;', '']
open(os.path.join(here, 'out', 'import_courses.sql'), 'w').write('\n'.join(sql))
print({c['slug']: len(c['chapters']) for c in courses})
