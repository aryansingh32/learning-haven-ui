"""Builds content/drafts/out/problems.json and import_problems.sql from the p_*.py modules.

    python3 build_problems.py

Expected outputs come from each reference solution. Run verify_problems.mjs afterwards
to push every reference through the real judge.
"""
import glob, importlib, inspect, json, os, re, sys, textwrap
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import build_tests, starters

here = os.path.dirname(os.path.abspath(__file__))
problems, slugs = [], set()
for f in sorted(glob.glob(os.path.join(here, 'p_*.py'))):
    mod = importlib.import_module(os.path.basename(f)[:-3])
    for p in mod.PROBLEMS:
        assert p.slug not in slugs, f'duplicate slug {p.slug}'
        assert p.difficulty in ('easy', 'medium', 'hard'), p.slug
        assert p.ref.__name__ == p.name, f'{p.slug}: reference must be named {p.name}'
        slugs.add(p.slug)
        problems.append({
            'slug': p.slug, 'title': p.title, 'topic': p.topic, 'difficulty': p.difficulty,
            'description': p.description, 'constraints': p.constraints, 'hints': p.hints,
            'solution_explanation': p.explanation, 'time_complexity': p.time, 'space_complexity': p.space,
            'is_premium': p.premium, 'compare': p.compare, 'name': p.name,
            'starter_code': starters(p), 'tests': build_tests(p),
            'reference_python': textwrap.dedent(inspect.getsource(p.ref)),
        })

os.makedirs(os.path.join(here, 'out'), exist_ok=True)
json.dump(problems, open(os.path.join(here, 'out', 'problems.json'), 'w'), indent=1, ensure_ascii=False)


def q(s):  # SQL string literal
    return "E'" + s.replace('\\', '\\\\').replace("'", "''").replace('\n', '\\n') + "'"


sql = ['-- DRAFT content import: practice problems. NOT a migration — run by hand after the team has reviewed',
       '-- content/drafts/out/problems.json. Safe to re-run: existing slugs are skipped.',
       '-- Generated by content/drafts/build_problems.py. Do not edit by hand.', 'begin;', '']
for i, p in enumerate(problems):
    hints = 'array[' + ','.join(q(h) for h in p['hints']) + ']::text[]'
    sql.append(f"""with ins as (
  insert into public.problems (slug, title, description, difficulty, topic, hints, constraints, solution_explanation,
                               time_complexity, space_complexity, is_premium, order_index, starter_code, judge_config)
  select {q(p['slug'])}, {q(p['title'])}, {q(p['description'])}, {q(p['difficulty'])}, {q(p['topic'])}, {hints}, {q(p['constraints'])},
         {q(p['solution_explanation'])}, {q(p['time_complexity'])}, {q(p['space_complexity'])}, {str(p['is_premium']).lower()},
         (select coalesce(max(order_index), 0) + 1 from public.problems), {q(json.dumps(p['starter_code']))}::jsonb,
         jsonb_build_object('compare', {q(p['compare'])})
   where not exists (select 1 from public.problems where slug = {q(p['slug'])})
  returning id)
insert into public.problem_test_cases (problem_id, input, expected_output, is_sample, explanation, sort_order)
select ins.id, t.input, t.expected, t.is_sample, null, t.ord
  from ins, (values""")
    rows = [f"({q(t['input'])}, {q(t['expected'])}, {str(t['sample']).lower()}, {n + 1})" for n, t in enumerate(p['tests'])]
    sql.append(',\n'.join('    ' + r for r in rows))
    sql.append(') as t(input, expected, is_sample, ord);\n')
sql += ['commit;', '']
open(os.path.join(here, 'out', 'import_problems.sql'), 'w').write('\n'.join(sql))
print(f'{len(problems)} problems, {sum(len(p["tests"]) for p in problems)} tests')
