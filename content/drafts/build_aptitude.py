"""Builds out/aptitude.json and out/import_aptitude.sql: a tagged question bank plus 8 draft mock tests.
    python3 build_aptitude.py
Every question is validated: 4 distinct options, exactly one correct, answer present.
"""
import hashlib, json, os, random, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aptitude_gen as G
from aptitude_verbal import V

here = os.path.dirname(os.path.abspath(__file__))
rng = random.Random(2026)
slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
PER = {'Quantitative': 8, 'Logical Reasoning': 10}

bank, seen = [], set()
def add(d):
    opts = [d['correct']] + d['wrong']
    if len(opts) != 4 or len(set(opts)) != 4:
        return False  # colliding distractors: skip this draw
    assert d['difficulty'] in ('easy', 'medium', 'hard')
    key = d['body'].strip().lower()
    if key in seen:
        return False
    seen.add(key)
    order = list(range(4)); rng.shuffle(order)
    options = [{'id': 'abcd'[i], 'text': opts[o]} for i, o in enumerate(order)]
    correct = 'abcd'[order.index(0)]
    h = hashlib.sha1(key.encode()).hexdigest()[:10]
    bank.append({**d, 'options': options, 'correct_id': correct, 'hash': h})
    return True

for gens, section in ((G.QUANT, 'Quantitative'), (G.REASONING, 'Logical Reasoning')):
    for g in gens:
        got, tries = 0, 0
        while got < PER[section] and tries < 400:
            tries += 1
            try:
                got += add(g(rng))
            except G.Inexact:
                continue
        if got < PER[section]:
            print('LOW', g.__name__, got)
for t, diff, body, ok, wrong, why in V:
    add(dict(topic=t, section='Verbal Ability', difficulty=diff, body=body, correct=ok, wrong=wrong, explanation=why))

by = {s: [b for b in bank if b['section'] == s] for s in ('Quantitative', 'Logical Reasoning', 'Verbal Ability')}
print({k: len(v) for k, v in by.items()}, 'total', len(bank))

# 8 mock tests: spread topics, no question reused across mocks while the bank allows.
SPEC = [('Quantitative', 14, 1500), ('Logical Reasoning', 10, 1200), ('Verbal Ability', 5, 450)]
pools = {}
for s, rows in by.items():
    rows = rows[:]; rng.shuffle(rows)
    rows.sort(key=lambda r: r['topic'])  # round-robin across topics below
    topics = {}
    for r in rows: topics.setdefault(r['topic'], []).append(r)
    order = []
    while any(topics.values()):
        for t in list(topics):
            if topics[t]: order.append(topics[t].pop(0))
    pools[s] = order
mocks = []
for m in range(8):
    secs = []
    for s, n, secs_ in SPEC:
        take = [pools[s].pop(0) for _ in range(n) if pools[s]]
        secs.append({'name': s, 'duration_seconds': secs_, 'hashes': [r['hash'] for r in take]})
    mocks.append({'title': f'Placement Aptitude Mock {m + 1}', 'slug': f'placement-aptitude-mock-{m + 1}', 'sections': secs})
assert all(len(s['hashes']) == n for mk in mocks for s, (_, n, _) in zip(mk['sections'], SPEC)), 'bank too small for the mocks'

os.makedirs(os.path.join(here, 'out'), exist_ok=True)
json.dump({'questions': bank, 'mocks': mocks}, open(os.path.join(here, 'out', 'aptitude.json'), 'w'), indent=1, ensure_ascii=False)

def q(s): return "E'" + s.replace('\\', '\\\\').replace("'", "''").replace('\n', '\\n') + "'"
sql = ['-- DRAFT content import: aptitude question bank + 8 mock tests (all unpublished). NOT a migration.',
       '-- Run by hand after review of content/drafts/out/aptitude.json. Re-runnable: questions are matched by their bank-<hash> tag.',
       '-- Generated by content/drafts/build_aptitude.py. Do not edit by hand.', 'begin;', '',
       "insert into public.exam_categories (slug, name, description) values ('placement-aptitude', 'Placement Aptitude', 'Quantitative, reasoning and verbal practice for campus placements')",
       'on conflict (slug) do nothing;', '',
       "insert into public.test_series (exam_category_id, slug, title, description, is_free, price, is_published)",
       "select id, 'placement-aptitude-mocks', 'Placement Aptitude Mock Series', 'Eight timed, sectional mock tests: quantitative, logical reasoning and verbal ability.', false, 0, false",
       "from public.exam_categories where slug = 'placement-aptitude'",
       "and not exists (select 1 from public.test_series where slug = 'placement-aptitude-mocks');", '']
for b in bank:
    tags = ['aptitude', slug(b['section']), slug(b['topic']), 'bank-' + b['hash']]
    opts = json.dumps(b['options'], ensure_ascii=False)
    sql.append(f"""insert into public.testseries_questions (question_type, body, options, correct_options, marks, negative_marks, topic, difficulty, explanation, tags)
select 'mcq', {q(b['body'])}, {q(opts)}::jsonb, '["{b['correct_id']}"]'::jsonb, 1, 0.25, {q(b['topic'])}, {q(b['difficulty'])}, {q(b['explanation'])}, {q('{' + ','.join(tags) + '}')}::text[]
where not exists (select 1 from public.testseries_questions where tags @> array['bank-{b['hash']}']);""")
sql.append('')
for mk in mocks:
    total = sum(s['duration_seconds'] for s in mk['sections'])
    sql.append(f"""insert into public.tests (test_series_id, slug, title, instructions, duration_seconds, is_sectional, section_time_locked, is_free, is_published, sort_order)
select ts.id, {q(mk['slug'])}, {q(mk['title'])}, {q('Three sections: Quantitative, Logical Reasoning and Verbal Ability. Each correct answer earns 1 mark; each wrong answer loses 0.25. Unanswered questions score 0.')}, {total}, true, false, {'true' if mk['slug'].endswith('-1') else 'false'}, false, {mk['slug'].rsplit('-', 1)[1]}
from public.test_series ts where ts.slug = 'placement-aptitude-mocks'
and not exists (select 1 from public.tests where slug = {q(mk['slug'])});""")
    for i, s in enumerate(mk['sections']):
        sql.append(f"""insert into public.test_sections (test_id, name, sort_order, duration_seconds)
select t.id, {q(s['name'])}, {i + 1}, {s['duration_seconds']} from public.tests t where t.slug = {q(mk['slug'])}
and not exists (select 1 from public.test_sections x where x.test_id = t.id and x.name = {q(s['name'])});""")
        hs = ','.join(f"'bank-{h}'" for h in s['hashes'])
        sql.append(f"""insert into public.test_questions (test_id, question_id, section_id, sort_order)
select t.id, qq.id, sec.id, {(i + 1) * 100} + row_number() over (order by qq.id)
from public.tests t
join public.test_sections sec on sec.test_id = t.id and sec.name = {q(s['name'])}
join public.testseries_questions qq on qq.tags && array[{hs}]::text[]
where t.slug = {q(mk['slug'])} and not exists (select 1 from public.test_questions x where x.test_id = t.id and x.question_id = qq.id);""")
sql += ['commit;', '']
open(os.path.join(here, 'out', 'import_aptitude.sql'), 'w').write('\n'.join(sql))
print('mocks', len(mocks), 'sql bytes', os.path.getsize(os.path.join(here, 'out', 'import_aptitude.sql')))
